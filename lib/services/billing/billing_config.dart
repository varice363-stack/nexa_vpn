/// Конфигурация оплаты.
///
/// Пока не подключён реальный платёжный провайдер (ЮKassa требует
/// оформленной самозанятости/ИП), приложение НЕ имитирует покупку.
/// Тарифы и цены показываются честно, а кнопка оплаты заменяется
/// пометкой «Оплата скоро».
///
/// Когда провайдер заработает, продажи включаются одним флагом сборки,
/// без правки кода:
///
///   flutter build apk --dart-define=PAYMENTS_ENABLED=true
///
/// Флаг сознательно выключен по умолчанию: сборка, случайно ушедшая
/// в стор, не сможет взять деньги при неготовом бэкенде.
abstract final class BillingConfig {
  /// Включены ли продажи внутри приложения.
  static const bool paymentsEnabled = bool.fromEnvironment(
    'PAYMENTS_ENABLED',
    defaultValue: false,
  );

  /// Валюта отображения цен по умолчанию.
  ///
  /// Backend отдаёт валюту вместе с тарифом; это значение используется
  /// только для офлайн-каталога, когда API недоступен.
  static const String defaultCurrency = 'RUB';
}

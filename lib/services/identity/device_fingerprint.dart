import 'package:flutter/services.dart';

/// Обезличенный признак устройства — защита пробного периода от переустановки.
///
/// Проблема, которую это решает: код устройства (`MOROK-…`) хранится в
/// защищённом хранилище Android и **стирается вместе с приложением**. Человек
/// мог удалить приложение, поставить заново — получить новый код, новый аккаунт
/// и второй бесплатный пробный период. Бесконечно.
///
/// Признак здесь устроен иначе: он берётся у операционной системы
/// (`Settings.Secure.ANDROID_ID`), переживает удаление приложения и **не
/// совпадает** между разными телефонами. Наружу уходит только необратимый
/// хеш — сам идентификатор остаётся в телефоне:
///
///   `SHA-256("morok:v1:" + ANDROID_ID)`
///
/// Соль `morok:v1` не даёт сопоставить хеш с базой утечек других приложений,
/// которые тоже считают хеш от ANDROID_ID.
///
/// Границы честно:
///  * сброс телефона к заводским настройкам меняет идентификатор — после
///    сброса устройство для сервера новое (это осознанно: сброс — редкое и
///    разрушительное действие, а не «удалил и поставил заново»);
///  * на платформах без этого канала (тесты, iOS, desktop) признак
///    отсутствует — сервер тогда ведёт себя как раньше и пробный выдаёт,
///    то есть отсутствие признака ничего не ломает.
abstract final class DeviceFingerprint {
  /// Тот же канал, что и у остальных нативных вызовов приложения —
  /// один канал проще держать в голове, чем три.
  static const MethodChannel _channel =
      MethodChannel('com.morokvpn.app/vpn_settings');

  static String? _cached;
  static bool _asked = false;

  /// Хеш признака устройства или null, если платформа его не даёт.
  ///
  /// Результат кешируется: значение не меняется в течение жизни процесса,
  /// а вызов идёт через платформенный канал.
  static Future<String?> get() async {
    if (_asked) return _cached;
    _asked = true;
    try {
      final value = await _channel.invokeMethod<String>('deviceFingerprint');
      if (value != null && value.isNotEmpty) {
        _cached = value;
      }
    } on MissingPluginException {
      // Тесты и сборки под другие платформы: признак недоступен.
    } on PlatformException {
      // Нативная часть ответила ошибкой — работаем без признака.
    } catch (_) {
      // Канал может быть недоступен и до инициализации движка (тесты). Это
      // вспомогательный признак: его отсутствие не повод ломать регистрацию.
    }
    return _cached;
  }

  /// Сбросить кеш (только для тестов).
  static void resetCacheForTests() {
    _cached = null;
    _asked = false;
  }
}
